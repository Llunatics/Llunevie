    /**
     * Dynamically localizes canonical shelf keys ("Koleksi Fisik" <-> "Physical Collection")
     * so switching between Indonesia and English translates shelf badges everywhere 1:1.
     */
    fun localizeShelfName(rawShelf: String): String {
        val trimmed = rawShelf.trim()
        if (trimmed.equals("all", ignoreCase = true) || trimmed.equals("semua", ignoreCase = true)) {
            return shelfAll
        }
        if (trimmed.equals("Koleksi Fisik", ignoreCase = true) ||
            trimmed.equals("Physical Collection", ignoreCase = true)
        ) {
            return shelfPhysicalLabel
        }
        return trimmed.ifBlank { "eReader" }
    }
}

fun canonicalShelfKey(shelfName: String): String {
    val trimmed = shelfName.trim()
    return if (trimmed.equals("Physical Collection", ignoreCase = true) ||
        trimmed.equals("Koleksi Fisik", ignoreCase = true)
    ) {
        "Koleksi Fisik"
    } else {
        trimmed.ifBlank { "eReader" }
    }
}

fun shelfMatchesFilter(bookShelf: String, activeShelfFilter: String): Boolean {
    return canonicalShelfKey(bookShelf).equals(canonicalShelfKey(activeShelfFilter), ignoreCase = true)
}

